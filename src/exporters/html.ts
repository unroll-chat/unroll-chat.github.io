export const htmlExporter: Exporter = {
  format: 'html',
  label: 'HTML',
  extension: 'html',
  mimeType: 'text/html',

  export(conversation: Conversation, options?: ExportOptions): string {
    const opts = ExportOptionsSchema.parse(options ?? {});
    const messages = filterMessages(conversation.messages, opts);

    let metaBlock = '';
    if (opts.includeMetadata) {
      const items: string[] = [
        `<strong>Source:</strong> ${esc(conversation.source)}`,
        `<strong>Vendor:</strong> ${esc(conversation.vendor)}`,
        `<strong>Exported:</strong> ${esc(conversation.exportedAt)}`,
      ];
      if (conversation.metadata.model) {
        items.push(`<strong>Model:</strong> ${esc(conversation.metadata.model)}`);
      }
      if (conversation.metadata.createdAt) {
        items.push(`<strong>Created:</strong> ${esc(conversation.metadata.createdAt)}`);
      }
      items.push(`<strong>Messages:</strong> ${conversation.metadata.messageCount}`);
      metaBlock = `<div class="meta">${items.join('<br>')}</div>`;
    }

    const messageDivs = messages
      .map((msg) => {
        const html = contentToHtml(msg.content);
        return `<div class="msg ${msg.role}"><div class="role-label">${esc(msg.role)}</div>${html}</div>`;
      })
      .join('\n');

    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(conversation.title)}</title>
<style>${CSS}</style>
</head>
<body>
<div class="container">
<h1>${esc(conversation.title)}</h1>
${metaBlock}
<div class="messages">
${messageDivs}
</div>
<div class="footer">Generated by unroll-chat</div>
</div>
</body>
</html>`;
  },
};
