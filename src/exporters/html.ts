/** Escape HTML special chars */
function esc(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Convert content to HTML — preserves code fences as <pre><code> blocks
 * and turns plain newlines into <br>.
 */
function contentToHtml(content: string): string {
  const parts: string[] = [];
  const codeBlockRegex = /```(\w*)\n([\s\S]*?)```/g;
  let lastIndex = 0;

  for (const match of content.matchAll(codeBlockRegex)) {
    // Text before the code block
    const before = content.slice(lastIndex, match.index);
    if (before) {
      parts.push(esc(before).replace(/\n/g, '<br>'));
    }

    const lang = match[1] ?? '';
    const code = esc(match[2]!);
    parts.push(
      `<pre class="code-block"><code${lang ? ` data-lang="${esc(lang)}"` : ''}>${code}</code></pre>`,
    );
    lastIndex = match.index! + match[0].length;
  }

  // Remaining text after the last code block
  const remaining = content.slice(lastIndex);
  if (remaining) {
    parts.push(esc(remaining).replace(/\n/g, '<br>'));
  }

  return parts.join('');
}

